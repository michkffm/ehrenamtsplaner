export function translate(language: Language, key: MessageKey, values: Record<string, string | number> = {}): string {
  const message: string = (language === 'en' ? en : de)[key];
  return message.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}
